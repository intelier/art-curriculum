function peEl(mode) {
  const cell = arr => {
    const pick = mode === "all" ? arr : mode === "one" ? [arr[Math.random() * arr.length | 0]] : [];
    return arr.map(e => `<div>⋅ ${pick.includes(e) ? `<span class="bl" tabindex="0">${esc(e)}</span>` : esc(e)}</div>`).join("");
  };
  return `<div class="tscroll"><table class="ct-table tg"><thead><tr><th>영역</th><th>범주</th>${PE_GRADES.map(g => `<th>${g}</th>`).join("")}</tr></thead><tbody>${PE_AREAS.map(ar => CATS.map((c, ci) =>
    `<tr>${ci === 0 ? `<th class="side" rowspan="3">${esc(ar)}</th>` : ""}<th class="side">${CAT_LABEL[c]}</th>${PE_GRADES.map(g => `<td class="ex">${cell(PE_EL[ar][g][c])}</td>`).join("")}</tr>`).join("")).join("")}</tbody></table></div>`;
}
function peActs(g, mode) {
  const rows = PE_ACTS[g].rows;
  const span = i => rows.filter(r => r[0] === rows[i][0]).length;
  return `<div class="tscroll"><table class="ct-table t1"><thead><tr><th>영역</th><th>세부 영역</th><th>신체활동 예시</th></tr></thead><tbody>${rows.map(([ar, sub, ts], i) =>
    `<tr>${i === 0 || rows[i - 1][0] !== ar ? `<th class="side" rowspan="${span(i)}">${esc(ar)}</th>` : ""}<th class="side">${esc(sub)}</th><td class="ex">${ts.map(t => `<div>∙ ${sentHTML(t, mode)}</div>`).join("")}</td></tr>`).join("")}</tbody></table></div>`;
}

